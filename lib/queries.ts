// SQL the app runs per request. Connection already uses SITE_SCOUT.APP.
// Bind order and returned columns above each query. Columns come back UPPERCASE.
// H3 ids are strings; wrap them with H3_STRING_TO_INT before H3 geo functions.

// binds: [type] -> H3, COMPETITORS, STUDENTS, WORKERS, RESIDENTS, SHOPPERS, LAT, LNG
export const HEXES_SQL = `
SELECT H3, COMPETITORS, STUDENTS, WORKERS, RESIDENTS, SHOPPERS, LAT, LNG
FROM HEX_FEATURES
WHERE BUSINESS_TYPE = ?`;

// binds: [type, h3] -> one row, same columns
export const HEX_SQL = `
SELECT H3, COMPETITORS, STUDENTS, WORKERS, RESIDENTS, SHOPPERS, LAT, LNG
FROM HEX_FEATURES
WHERE BUSINESS_TYPE = ? AND H3 = ?`;

// binds: [h3, type] -> NAME, CATEGORY, LAT, LNG, DISTANCE_M
export const COMPETITORS_SQL = `
SELECT p.NAME, p.CATEGORY, p.LAT, p.LNG,
       ROUND(ST_DISTANCE(p.GEOG, H3_CELL_TO_POINT(H3_STRING_TO_INT(?)))) AS DISTANCE_M
FROM PLACES p
JOIN COMPETITOR_CATEGORIES c ON p.CATEGORY = c.CATEGORY
WHERE c.BUSINESS_TYPE = ? AND p.NAME IS NOT NULL
ORDER BY DISTANCE_M
LIMIT 5`;

// binds: [h3] -> CATEGORY, DRIVER_GROUP, N
export const DRIVERS_SQL = `
SELECT p.CATEGORY, d.DRIVER_GROUP, COUNT(*) AS N
FROM PLACES p
JOIN DRIVER_CATEGORIES d ON p.CATEGORY = d.CATEGORY
WHERE p.H3 = ?
GROUP BY p.CATEGORY, d.DRIVER_GROUP
ORDER BY N DESC
LIMIT 8`;

// binds: [] -> CATEGORY, N (the 300 most common categories in the demo area)
export const CATEGORIES_SQL = `
SELECT CATEGORY, COUNT(*) AS N
FROM PLACES
GROUP BY 1
ORDER BY N DESC
LIMIT 300`;

// binds: [categoriesJson] -> same columns as HEXES_SQL.
// Driver counts don't depend on type, so the boba rows supply them; competitors come from the given categories.
export const CUSTOM_HEXES_SQL = `
WITH d AS (SELECT H3, STUDENTS, WORKERS, RESIDENTS, SHOPPERS, LAT, LNG FROM HEX_FEATURES WHERE BUSINESS_TYPE = 'boba'),
c AS (SELECT H3, COUNT(*) AS COMPETITORS FROM PLACES WHERE ARRAY_CONTAINS(CATEGORY::VARIANT, PARSE_JSON(?)) GROUP BY H3)
SELECT d.H3, COALESCE(c.COMPETITORS, 0) AS COMPETITORS, d.STUDENTS, d.WORKERS, d.RESIDENTS, d.SHOPPERS, d.LAT, d.LNG
FROM d LEFT JOIN c ON c.H3 = d.H3`;

// binds: [h3, categoriesJson] -> NAME, CATEGORY, LAT, LNG, DISTANCE_M
export const CUSTOM_COMPETITORS_SQL = `
SELECT p.NAME, p.CATEGORY, p.LAT, p.LNG,
       ROUND(ST_DISTANCE(p.GEOG, H3_CELL_TO_POINT(H3_STRING_TO_INT(?)))) AS DISTANCE_M
FROM PLACES p
WHERE ARRAY_CONTAINS(p.CATEGORY::VARIANT, PARSE_JSON(?)) AND p.NAME IS NOT NULL
ORDER BY DISTANCE_M
LIMIT 5`;

// binds: ["%query%", "query%"] -> NAME, CATEGORY, LAT, LNG, H3
export const SEARCH_SQL = `
SELECT NAME, CATEGORY, LAT, LNG, H3
FROM PLACES
WHERE NAME ILIKE ?
ORDER BY IFF(NAME ILIKE ?, 0, 1), LENGTH(NAME)
LIMIT 8`;
